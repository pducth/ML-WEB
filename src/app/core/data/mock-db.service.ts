import { HttpClient } from '@angular/common/http';
import { Injectable, computed, inject, signal } from '@angular/core';
import { firstValueFrom } from 'rxjs';
import type { MockDatabase } from '../models';

const STORAGE_KEY = 'haircare-insight:db';
const SEED_URL = '/assets/data/haircare-db.json';

/** Error raised by domain services when a business rule (BR-*) rejects an action. */
export class DomainError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'DomainError';
  }
}

export function errorMessage(error: unknown, fallback = 'Something went wrong. Please try again.'): string {
  return error instanceof DomainError || error instanceof Error ? error.message : fallback;
}

/**
 * Browser-side mock backend. The database is seeded from `public/assets/data/haircare-db.json`
 * (generated by `scripts/build_mock_db.py`) and persisted to localStorage so the storefront and
 * the admin portal share one consistent state — also across browser tabs.
 *
 * Every write goes through {@link mutate}: the callback receives a draft copy and the change is
 * committed only if the callback finishes without throwing. Multi-step business operations
 * (reserve stock + create order + consume voucher…) are therefore atomic.
 */
@Injectable({ providedIn: 'root' })
export class MockDbService {
  private readonly http = inject(HttpClient);
  private readonly state = signal<MockDatabase | null>(null);
  private seedGeneratedAt = '';

  readonly ready = computed(() => this.state() !== null);

  /** Reactive read access. Only call after the app initializer resolved {@link load}. */
  readonly db = computed(() => {
    const db = this.state();
    if (!db) throw new Error('Mock database has not been loaded yet.');
    return db;
  });

  async load(): Promise<void> {
    const seed = await firstValueFrom(this.http.get<MockDatabase>(SEED_URL));
    this.seedGeneratedAt = seed.generatedAt;
    const stored = this.readStorage();
    // A regenerated seed replaces the local copy so schema changes never mix with stale data.
    this.state.set(stored && stored.generatedAt === seed.generatedAt ? stored : seed);
    if (!stored || stored.generatedAt !== seed.generatedAt) this.persist();
    if (typeof window !== 'undefined') {
      window.addEventListener('storage', (event) => {
        if (event.key === STORAGE_KEY) this.syncFromStorage();
      });
    }
  }

  mutate<T>(change: (draft: MockDatabase) => T): T {
    const draft = structuredClone(this.db());
    const result = change(draft);
    this.state.set(draft);
    this.persist();
    return result;
  }

  /** Re-reads the persisted copy (used for payment polling and cross-tab updates). */
  syncFromStorage(): void {
    const stored = this.readStorage();
    if (stored && stored.generatedAt === this.seedGeneratedAt) this.state.set(stored);
  }

  async reset(): Promise<void> {
    try {
      localStorage.removeItem(STORAGE_KEY);
    } catch {
      // storage unavailable: nothing to clear
    }
    await this.load();
  }

  private readStorage(): MockDatabase | null {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      return raw ? (JSON.parse(raw) as MockDatabase) : null;
    } catch {
      return null;
    }
  }

  private persist(): void {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(this.state()));
    } catch {
      // Quota exceeded or private mode: keep working in memory for this session.
    }
  }
}

export function newId(prefix: string): string {
  return `${prefix}-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 7)}`;
}

export function nowIso(): string {
  return new Date().toISOString();
}
